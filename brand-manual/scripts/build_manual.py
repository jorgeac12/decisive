"""Build manual.html, the browsable brand manual, from a validated kit (stdlib only).

    python scripts/build_manual.py path/to/brand           # writes path/to/brand/manual.html
    python scripts/build_manual.py path/to/brand --check   # exit 1 if manual.html is out of date

The page has no script. Every value from the kit is HTML-escaped, colors and
fonts reach the stylesheet only after the validator's character checks, and a
Content-Security-Policy pins the one stylesheet by hash. The build refuses a
kit with validation errors.
"""
import base64
import hashlib
import html
import re
import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import check_kit, color_value, contrast  # noqa: E402

CSS = Path(__file__).resolve().parents[1] / "assets" / "manual.css"
L = {
    "en": dict(manual="Brand manual", provisional="Provisional logo: typographic wordmark. Hire a designer for the final mark.",
               no_logo="No logo file yet.", logos="Logo", colors="Colors", contrast="Checked text pairs", pair="Text on background",
               ratio="Ratio", needs="Needs", typography="Typography", spacing="Spacing and radius", book="Brand book",
               photos="Photo library", none_photos="No photos indexed yet.", origin="Origin", direction="Direction",
               sensitive="check before publishing", best="best of group", token="Token", value="Value", usage="Usage",
               generated="Generated by Brand Manual (Decisive) from tokens.json, brand.md and photos/index.json. Edit those files, not this page.",
               on_light="on light", on_dark="on dark", text_space="text space", large="large text"),
    "pt": dict(manual="Manual de marca", provisional="Logotipo provisório: wordmark tipográfico. Contrate um designer para a marca definitiva.",
               no_logo="Ainda sem arquivo de logotipo.", logos="Logotipo", colors="Cores", contrast="Pares de texto conferidos",
               pair="Texto sobre fundo", ratio="Contraste", needs="Mínimo", typography="Tipografia", spacing="Espaçamento e raio",
               book="Livro da marca", photos="Acervo de fotos", none_photos="Nenhuma foto indexada ainda.", origin="Origem",
               direction="Direção", sensitive="conferir antes de publicar", best="melhor do grupo", token="Token", value="Valor",
               usage="Uso", generated="Gerado pela Brand Manual (Decisive) a partir de tokens.json, brand.md e photos/index.json. Edite esses arquivos, não esta página.",
               on_light="no claro", on_dark="no escuro", text_space="espaço para texto", large="texto grande"),
}
E = html.escape


def inline(text):
    t = E(text, quote=True)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", t)


def markdown(text):
    """Small, escaping-first subset: headings, paragraphs, lists, tables, bold, code. Links render as text."""
    out, para, lst, tbl = [], [], [], []

    def flush():
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()
        if lst:
            out.append("<ul>" + "".join(f"<li>{inline(x)}</li>" for x in lst) + "</ul>")
            lst.clear()
        if tbl:
            rows = [[c.strip() for c in r.strip().strip("|").split("|")] for r in tbl]
            rows = [r for r in rows if not all(re.fullmatch(r":?-{2,}:?", c) for c in r)]
            if rows:
                head = "".join(f"<th>{inline(c)}</th>" for c in rows[0])
                body = "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in rows[1:])
                out.append(f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")
            tbl.clear()

    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"^(#{1,4})\s+(.*)$", s)
        if m:
            flush()
            lvl = min(len(m.group(1)) + 2, 4)
            out.append(f"<h{lvl}>{inline(m.group(2))}</h{lvl}>")
        elif re.match(r"^[-*]\s+", s):
            if para or tbl:
                flush()
            lst.append(re.sub(r"^[-*]\s+", "", s))
        elif s.startswith("|"):
            if para or lst:
                flush()
            tbl.append(s)
        elif not s:
            flush()
        else:
            if lst or tbl:
                flush()
            para.append(s)
    flush()
    return "\n".join(out)


def px_cap(value, cap=40):
    m = re.match(r"^(\d+(?:\.\d+)?)(px)?$", str(value))
    return f"{min(float(m.group(1)), cap):g}px" if m else "24px"


def build(kit):
    kit = Path(kit)
    errors, _, data = check_kit(kit)
    errors = [e for e in errors if not e.startswith("manual.html")]
    if errors:
        raise SystemExit("kit has validation errors; run validate.py:\n  " + "\n  ".join(errors))
    tk, meta = data["tokens"], data["tokens"]["meta"]
    t = L["pt"] if meta["lang"].lower().startswith("pt") else L["en"]
    themes = tk["color"]["themes"]
    tids = [x["id"] for x in themes]
    css, body = [CSS.read_text(encoding="utf-8")], []
    name = E(tk["name"])

    body.append(f"<h1>{name}</h1><p class=\"meta\">{t['manual']} · {t['direction']}: {E(meta['direction'])} · v{E(str(tk.get('version', 1)))}</p>")
    if meta["provisional_logo"]:
        body.append(f"<p class=\"banner\">{t['provisional']}</p>")

    body.append(f"<h2>{t['logos']}</h2>")
    imgs = [f for f in data["logos"] if not f.lower().endswith(".pdf")]
    if imgs:
        body.append("<div class=\"grid\">")
        for f in imgs:
            for mode in ("light", "dark"):
                body.append(f"<div class=\"card\"><div class=\"logo {mode}\"><img src=\"logos/{quote(f)}\" alt=\"{name}\"></div>"
                            f"<div class=\"body\"><p class=\"small\">{E(f)} · {t['on_' + mode]}</p></div></div>")
        body.append("</div>")
    else:
        body.append(f"<p>{t['no_logo']}</p>")

    body.append(f"<h2>{t['colors']}</h2><div class=\"grid\">")
    colors = {}
    for i, c in enumerate(tk["color"]["tokens"]):
        vals = color_value(c, tids)
        colors[c["name"]] = vals
        row = ""
        for j, tid in enumerate(tids):
            css.append(f".c{i}-{j}{{background:{vals[tid]}}}")
            row += f"<div class=\"sw c{i}-{j}\"></div>"
        hexes = " · ".join(E(vals[x].upper()) for x in tids)
        body.append(f"<div class=\"card\"><div class=\"swrow\">{row}</div><div class=\"body\"><p class=\"name\">{E(c['name'])}</p>"
                    f"<p class=\"small\"><code>{hexes}</code></p><p class=\"small\">{E(c['usage'])}</p>"
                    f"<p class=\"small\">{t['origin']}: {E(meta['origins'][c['name']])}</p></div></div>")
    body.append("</div>")
    if len(tids) > 1:
        body.append("<p class=\"meta\">" + " · ".join(E(x["name"]) for x in themes) + "</p>")
    body.append(f"<h3>{t['contrast']}</h3><table><thead><tr><th>{t['pair']}</th>"
                + "".join(f"<th>{t['ratio']} ({E(x['name'])})</th>" for x in themes) + f"<th>{t['needs']}</th></tr></thead><tbody>")
    for p in meta["contrast_pairs"]:
        need = "3:1 (" + t["large"] + ")" if p.get("large") is True else "4.5:1"
        cells = "".join(f"<td class=\"pass\">{contrast(colors[p['text']][x], colors[p['on']][x]):.1f}:1</td>" for x in tids)
        body.append(f"<tr><td>{E(p['text'])} / {E(p['on'])}</td>{cells}<td>{need}</td></tr>")
    body.append("</tbody></table>")

    body.append(f"<h2>{t['typography']}</h2><div class=\"grid\">")
    k = 0
    for g in tk["type"].get("groups", []):
        fam = tk["type"]["families"][g["family"]]
        for s in g["styles"]:
            rule = f".t{k}{{font-family:{fam};font-size:{px_cap(s['fontSize'])};line-height:1.15"
            if "fontWeight" in s:
                rule += f";font-weight:{s['fontWeight']}"
            css.append(rule + "}")
            spec = " · ".join(E(str(s[x])) for x in ("fontSize", "lineHeight", "fontWeight") if x in s)
            body.append(f"<div class=\"card\"><div class=\"specimen t{k}\">{name}</div><div class=\"body\"><p class=\"name\">{E(s['name'])}</p>"
                        f"<p class=\"small\">{E(g['name'])} · {E(fam)}</p><p class=\"small\"><code>{spec}</code></p></div></div>")
            k += 1
    body.append("</div>")

    rows = [(fam, s) for fam in ("spacing", "radius") for s in (tk.get(fam) or {}).get("tokens", [])]
    if rows:
        body.append(f"<h2>{t['spacing']}</h2><table><thead><tr><th>{t['token']}</th><th>{t['value']}</th><th>{t['usage']}</th></tr></thead><tbody>")
        for _, s in rows:
            body.append(f"<tr><td><code>{E(s['name'])}</code></td><td>{E(str(s['value']))}</td><td>{E(str(s.get('usage', '')))}</td></tr>")
        body.append("</tbody></table>")

    body.append(f"<h2>{t['book']}</h2>" + markdown(data["brand"]))

    body.append(f"<h2>{t['photos']}</h2>")
    photos = data["photos"] or []
    if photos:
        body.append("<div class=\"grid\">")
        for ph in photos:
            tags = [ph["type"], ph["orientation"], f"{t['text_space']}: {ph['text_space']}"] + ph["use"]
            chips = "".join(f"<span class=\"tag\">{E(x)}</span>" for x in tags)
            if ph.get("best_of_group"):
                chips += f"<span class=\"tag\">{t['best']}</span>"
            if ph.get("sensitive"):
                chips += f"<span class=\"tag warn\">{t['sensitive']}: {E(', '.join(ph['sensitive']))}</span>"
            body.append(f"<div class=\"card photo\"><img loading=\"lazy\" src=\"photos/{quote(ph['file'])}\" alt=\"{E(ph['desc'])}\">"
                        f"<div class=\"body\"><p class=\"name\">{E(ph['id'])}</p><p class=\"small\">{E(ph['desc'])}</p>{chips}</div></div>")
        body.append("</div>")
    else:
        body.append(f"<p>{t['none_photos']}</p>")
    body.append(f"<footer>{t['generated']}</footer>")

    style = "\n".join(css)
    digest = base64.b64encode(hashlib.sha256(style.encode("utf-8")).digest()).decode()
    fonts = meta.get("google_fonts") or []
    link = ""
    if fonts:
        q = "&".join("family=" + f.replace(" ", "+") + ":wght@400;700" for f in fonts)
        link = f"<link rel=\"stylesheet\" href=\"https://fonts.googleapis.com/css2?{q}&display=swap\">\n"
    csp = (f"default-src 'none'; img-src 'self' data:; style-src 'sha256-{digest}'"
           + (" https://fonts.googleapis.com; font-src https://fonts.gstatic.com" if fonts else "")
           + "; base-uri 'none'; form-action 'none'")
    return (f"<!doctype html>\n<html lang=\"{E(meta['lang'])}\">\n<head>\n<meta charset=\"utf-8\">\n"
            f"<meta http-equiv=\"Content-Security-Policy\" content=\"{csp}\">\n"
            f"<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n<title>{name} · {t['manual']}</title>\n"
            f"{link}<style>{style}</style>\n</head>\n<body>\n<main>\n" + "\n".join(body) + "\n</main>\n</body>\n</html>\n")


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__)
        sys.exit(2)
    out = Path(args[0]) / "manual.html"
    page = build(args[0])
    if "--check" in sys.argv:
        ok = out.is_file() and out.read_text(encoding="utf-8") == page
        print("manual.html is up to date" if ok else "manual.html is out of date: run build_manual.py")
        sys.exit(0 if ok else 1)
    out.write_text(page, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
